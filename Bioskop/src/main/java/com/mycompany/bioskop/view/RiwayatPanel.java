    private void btnLihatTiketActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLihatTiketActionPerformed

        // TODO add your handling code here:                                       
        int baris = tblRiwayat.getSelectedRow();

        if (baris == -1) {
            JOptionPane.showMessageDialog(
                this,
                "Silakan pilih pesanan terlebih dahulu!"
            );
            return;
        }

        int idPemesanan = Integer.parseInt(
            tblRiwayat.getValueAt(baris, 0).toString()
        );

        RiwayatRepository repository = new RiwayatRepository();
        List<Riwayat> data = repository.getRiwayatByUser(idUser);

        Riwayat riwayat = null;

        for (Riwayat r : data) {
            if (r.getIdPemesanan() == idPemesanan) {
                riwayat = r;
                break;
            }
        }

        if (riwayat == null) {
            JOptionPane.showMessageDialog(
                this,
                "Data tiket tidak ditemukan!"
            );
            return;
        }

        UserMainFrame frame = (UserMainFrame)
            javax.swing.SwingUtilities.getWindowAncestor(this);

        frame.tampilkanPanel(new TicketPanel(riwayat, idUser));
    }//GEN-LAST:event_btnLihatTiketActionPerformed


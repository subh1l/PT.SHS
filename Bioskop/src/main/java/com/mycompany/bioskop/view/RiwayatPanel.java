    private void tampilkanRiwayat() {
        RiwayatRepository repository = new RiwayatRepository();
        DefaultTableModel model = (DefaultTableModel) tblRiwayat.getModel();

        model.setRowCount(0);

        List<Riwayat> data =
            repository.getRiwayatByUser(idUser);

        for (Riwayat riwayat : data) {

            model.addRow(new Object[]{
                riwayat.getIdPemesanan(),
                riwayat.getFilm(),
                riwayat.getTanggal(),
                riwayat.getJam(),
                riwayat.getStudio(),
                riwayat.getKursi(),
                riwayat.getTotalHarga(),
                riwayat.getStatus()
            });
        }

        if (data.isEmpty()) {
            lblSubRiwayat.setText(
                "Belum ada riwayat pemesanan tiket."
            );
        } else {
            lblSubRiwayat.setText(
                "Daftar tiket yang pernah kamu pesan."
            );
        }
    }

